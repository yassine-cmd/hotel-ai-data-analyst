# ── Turn completion reporting (billing) ────────────────────────────────────
# Python is the single, authoritative reporter of turn completion. When a turn
# finishes, it POSTs the usage deltas to the client's Laravel instance. The
# endpoint dedupes on turn_uuid (unique index), so retries here are
# idempotent. This decouples billing from the SSE relay: a cut stream can no
# longer silently drop usage rows.

_completion_tasks: set = set()


def _completion_payload(meta: dict, client_id: str, session_id: str, user_ref: Optional[int]) -> dict:
    return {
        "client_id": client_id,
        "session_id": session_id,
        "user_ref": user_ref,
        "turn_uuid": meta.get("turn_uuid", ""),
        "usage": {
            "turn_tokens": meta.get("turn_tokens"),
            "turn_prompt_tokens": meta.get("turn_prompt_tokens"),
            "turn_completion_tokens": meta.get("turn_completion_tokens"),
            "turn_reasoning_tokens": meta.get("turn_reasoning_tokens"),
            "turn_cache_hit_tokens": meta.get("turn_cache_hit_tokens"),
            "turn_cache_miss_tokens": meta.get("turn_cache_miss_tokens"),
            "turn_cost_usd": meta.get("turn_cost_usd"),
        },
    }


async def _report_turn_completion(completion_url: str, delegation_token: str, payload: dict) -> None:
    headers = {
        "X-Delegation-Token": delegation_token,
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    tid = trace_id_var.get()
    if tid and tid != "-":
        headers["X-Trace-Id"] = tid
    for attempt in range(1, 4):
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.post(completion_url, headers=headers, json=payload)
            if resp.status_code < 400:
                logger.info("Turn completion reported | turn=%s status=%d", payload.get("turn_uuid"), resp.status_code)
                return
            logger.warning(
                "Turn completion rejected | turn=%s status=%d body=%.300s",
                payload.get("turn_uuid"), resp.status_code, resp.text or "",
            )
        except Exception as e:
            logger.warning(
                "Turn completion failed (attempt %d/3) | turn=%s | %s",
                attempt, payload.get("turn_uuid"), e,
            )
        if attempt < 3:
            await asyncio.sleep(0.5 * attempt)
    logger.error("Turn completion permanently failed | turn=%s | url=%s", payload.get("turn_uuid"), completion_url)


def _spawn_completion(meta: dict, req: QueryRequest, session_id: str) -> None:
    if not req.completion_url:
        return
    payload = _completion_payload(meta, req.client_id, session_id, req.user_ref)
    if not payload["turn_uuid"]:
        return
    task = asyncio.create_task(_report_turn_completion(req.completion_url, req.delegation_token, payload))
    _completion_tasks.add(task)
    task.add_done_callback(_completion_tasks.discard)


def _resolve_backend(setting: str, local_cls, **kwargs):
    # Only LOCAL is implemented. Fail loudly at startup on anything else rather
    # than silently running with no backend (which crashed later with confusing
    # NoneType errors).
    if setting != "LOCAL":
        raise ValueError(f"Unsupported backend '{setting}' for {local_cls.__name__}; only LOCAL is implemented")
    return local_cls(**kwargs)


