@app.middleware("http")
async def telemetry_middleware(request: Request, call_next):
    rid = request.headers.get("X-Request-ID") or uuid.uuid4().hex
    request_id_token = request_id_var.set(rid)
    trace_id_token = trace_id_var.set(request.headers.get("X-Trace-Id") or rid)
    client_id = request.path_params.get("client_id", "-")
    client_id_token = client_id_var.set(client_id)
    request.state.request_id = rid
    request.state.client_id = client_id
    start = time.perf_counter()
    try:
        response = await call_next(request)
        response.headers["X-Request-ID"] = rid
        return response
    finally:
        duration_ms = (time.perf_counter() - start) * 1000
        if duration_ms > 5000:
            logger.warning("Slow request | method=%s path=%s duration_ms=%.0f", request.method, request.url.path, duration_ms)
        request_id_var.reset(request_id_token)
        trace_id_var.reset(trace_id_token)
        client_id_var.reset(client_id_token)


