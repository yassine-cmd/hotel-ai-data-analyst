@app.post("/internal/analyze")
async def analyze_internal(request: Request):
    payload = await _verify_request(request, require_admin=False)
    try:
        req = QueryRequest(**payload)
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Invalid request: {e}")

    # Lazy client-key refresh: if this client isn't known yet, ask Laravel for
    # the latest key map (handles a brand-new instance before its admin reg).
    if not key_store.has_client(req.client_id):
        await _refresh_client_keys()
        if not key_store.has_client(req.client_id):
            logger.warning("Analyze rejected: unregistered client_id=%s", req.client_id)
            raise HTTPException(status_code=403, detail="Client not registered")

    data_plane_url = req.data_plane_url
    if not data_plane_url:
        raise HTTPException(status_code=400, detail="data_plane_url is required")
    if not data_plane_url.startswith(("http://", "https://")):
        raise HTTPException(status_code=400, detail="data_plane_url must be http:// or https://")

    if not req.delegation_token:
        raise HTTPException(status_code=400, detail="delegation_token is required")

    session_id = req.session_id or str(uuid.uuid4())

    delegation_store.store(req.client_id, session_id, req.delegation_token)

    logger.info("POST /internal/analyze | session=%s | datasource=%s | query=%s", session_id, req.datasource_id or "default", req.query[:100])

    async def event_generator():
        executor = executor_cache.acquire(data_plane_url, req.client_id)
        client_id_token = client_id_var.set(req.client_id)
        trace_id_token = trace_id_var.set(req.trace_id or trace_id_var.get() or "-")
        try:
            async for event in agent.analyze(
                req.query, session_id, req.client_id,
                schema=req.db_schema,
                sensitive_rules=req.sensitive_rules,
                datasource_id=req.datasource_id or "__default__",
                execution=req.execution,
                agent_style=req.agent_style,
                user_ref=req.user_ref,
                user_access=req.user_access,
                executor=executor,
            ):
                if event.get("type") == "error":
                    submit_event(
                        "error.analysis",
                        client_id=req.client_id,
                        level="error",
                        context={
                            "session_id": session_id,
                            "code": event.get("code"),
                            "message": event.get("message"),
                            "trace_id": req.trace_id,
                        },
                    )
                if event.get("type") == "done":
                    _spawn_completion(event.get("meta") or {}, req, session_id)
                yield sse_transport.encode(event)
        except asyncio.CancelledError:
            logger.info("Stream ended for session %s", session_id)
        except Exception as e:
            logger.error("Error in analyze stream: %s", e, exc_info=True)
            payload = stream_error(e)
            yield sse_transport.encode({
                "type": "error",
                "code": payload["code"],
                "message": payload["message"],
                "retryable": payload["retryable"],
                "detail": payload["detail"],
            })
        finally:
            executor_cache.release(data_plane_url)
            client_id_var.reset(client_id_token)
            trace_id_var.reset(trace_id_token)
    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
            "X-Content-Type-Options": "nosniff",
        },
    )


