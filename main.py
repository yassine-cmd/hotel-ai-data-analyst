class DelegationStore:
    """Per-session delegation tokens authorizing data-plane calls.

    Keyed by (client_id, session_id). Tokens are short-lived JWT-like strings
    signed by the client instance. The executor looks up the token by session
    and forwards it to Laravel instead of signing requests itself.
    """

    def __init__(self) -> None:
        self._tokens: dict[tuple[str, str], str] = {}

    def store(self, client_id: str, session_id: str, token: str) -> None:
        self._tokens[(client_id, session_id)] = token

    def get(self, client_id: str, session_id: str) -> str | None:
        return self._tokens.get((client_id, session_id))

    def remove(self, client_id: str, session_id: str) -> None:
        self._tokens.pop((client_id, session_id), None)

    def purge_session(self, session_id: str) -> None:
        self._tokens = {k: v for k, v in self._tokens.items() if k[1] != session_id}


_EXECUTOR_IDLE_TTL_SEC = 1800  # close executors idle (no active streams) for 30+ min


class ExecutorCache:
    """Reference-counted, URL-keyed executor cache with idle eviction.

    Each active analysis stream holds a ref via acquire()/release(). When the
    last ref drops, an idle timer starts; a background sweep closes and removes
    executors past the TTL. Pop-before-await in evict_idle closes the TOCTOU
    race: a concurrent acquire() after the pop just builds a fresh executor
    rather than bumping a doomed one's refcount.
    """

    def __init__(self, delegation_store: DelegationStore):
        self._delegation_store = delegation_store
        self._executors: dict[str, RemoteQueryExecutor] = {}
        self._refcount: dict[str, int] = {}
        self._last_idle: dict[str, float] = {}

    def acquire(self, url: str, client_id: str) -> RemoteQueryExecutor:
        url = (url or "").rstrip("/")
        if url not in self._executors:
            self._executors[url] = RemoteQueryExecutor(
                base_url=url,
                delegation_store=self._delegation_store,
            )
            logger.info("ExecutorCache: new executor for %s (client=%s)", url, client_id)
        self._refcount[url] = self._refcount.get(url, 0) + 1
        self._last_idle.pop(url, None)
        logger.debug("ExecutorCache: acquire %s (refs=%d)", url, self._refcount[url])
        return self._executors[url]

    def release(self, url: str) -> None:
        url = (url or "").rstrip("/")
        if url in self._refcount:
            self._refcount[url] = max(0, self._refcount[url] - 1)
            if self._refcount[url] == 0:
                self._last_idle[url] = time.monotonic()
            logger.debug("ExecutorCache: release %s (refs=%d)", url, self._refcount[url])

    async def evict_idle(self) -> None:
        now = time.monotonic()
        for url in list(self._executors.keys()):
            if self._refcount.get(url, 0) > 0:
                continue
            if now - self._last_idle.get(url, now) <= _EXECUTOR_IDLE_TTL_SEC:
                continue
            # Pop BEFORE await so a concurrent acquire() can't resurrect this entry.
            executor = self._executors.pop(url)
            self._refcount.pop(url, None)
            self._last_idle.pop(url, None)
            await executor.close()
            logger.info("ExecutorCache: evicted idle executor for %s", url)

    async def close(self) -> None:
        for ex in self._executors.values():
            await ex.close()
        self._executors.clear()
        self._refcount.clear()
        self._last_idle.clear()


