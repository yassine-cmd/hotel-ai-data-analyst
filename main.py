async def _verify_request(request: Request, require_admin: bool = False, client_id_override: str | None = None) -> dict:
    """Verify the Ed25519 signature on a request and return the parsed JSON body.

    Reads the raw body, recomputes the signed canonical string from the
    X-Timestamp header, and verifies against the caller's registered public key.
    Returns 403 on any failure (missing/expired headers, unknown caller, bad
    signature). When ``require_admin`` is True the caller must be the admin
    instance.

    ``client_id_override`` lets callers supply the client_id out-of-band (e.g.
    from the URL path for GET requests with no body). When provided, JSON parsing
    is skipped and an empty dict is returned.
    """
    body = await request.body()
    ts_header = request.headers.get("X-Timestamp")
    sig_header = request.headers.get("X-Signature")
    if not ts_header or not sig_header:
        logger.warning("Auth rejected: missing signature headers | path=%s", request.url.path)
        raise HTTPException(status_code=403, detail="Missing signature headers")
    try:
        timestamp = int(ts_header)
    except ValueError:
        logger.warning("Auth rejected: bad timestamp | path=%s", request.url.path)
        raise HTTPException(status_code=403, detail="Invalid timestamp")

    if require_admin:
        ok = key_store.verify_admin(body, sig_header, timestamp)
        identity = "admin"
    else:
        if client_id_override is not None:
            client_id = str(client_id_override)
        else:
            try:
                payload = json.loads(body)
            except json.JSONDecodeError:
                raise HTTPException(status_code=400, detail="Invalid JSON body")
            client_id = str(payload.get("client_id", ""))
        ok = key_store.verify_client(body, sig_header, client_id, timestamp)
        identity = f"client={client_id}"

    if not ok:
        logger.warning("Auth rejected: bad signature | %s path=%s", identity, request.url.path)
        submit_event(
            "security.auth_rejected",
            client_id=None,
            level="critical",
            context={"identity": identity, "path": request.url.path, "ip": request.client.host if request.client else None},
        )
        raise HTTPException(status_code=403, detail="Invalid signature")
    logger.debug("Auth ok: %s", identity)

    if require_admin or client_id_override is not None:
        return {}
    return payload


@asynccontextmanager
async def lifespan(app):
    logger.info("Application starting | host=%s:%d | model=%s", settings.APP_HOST, settings.APP_PORT, settings.LLM_MODEL)
    async with AsyncExitStack() as stack:
        stack.push_async_callback(executor_cache.close)

        # Register the admin key so admin API calls verify.
        if settings.ADMIN_PUBLIC_KEY:
            key_store.set_admin_key(settings.ADMIN_PUBLIC_KEY)

        # Load client public keys from the shared DB via Laravel. Python has no
        # DB connection, so Laravel is the source of truth and exposes them.
        await _refresh_client_keys()

        # Configure the system-audit event forwarder. When enabled, Python
        # relays its own events and those reported by client Laravel instances
        # to the admin instance's daily system-audit log file.
        if settings.EVENT_FORWARD_ENABLED and settings.ADMIN_LARAVEL_URL:
            # Pass the origin only; the forwarder appends the /api/internal/events path.
            target = settings.ADMIN_LARAVEL_URL.rstrip("/")
            configure_forwarder(target, settings.EVENT_FORWARD_THROTTLE_SECONDS)
            await get_forwarder().start()
            stack.push_async_callback(lambda: asyncio.ensure_future(get_forwarder().stop()))
            logger.info("Event forwarder active | target=%s | throttle=%ss", target, settings.EVENT_FORWARD_THROTTLE_SECONDS)
        else:
            logger.info("Event forwarder disabled")

        SessionManager.cleanup_stale_tmp_files(settings.SESSION_DIR)

        session_manager.start_cleanup()
        stack.push_async_callback(session_manager.shutdown)

        asset_manager.start_cleanup()
        stack.push_async_callback(asset_manager.shutdown)

        await sandbox.prewarm()
        stack.push_async_callback(sandbox.close)

        # Periodically refresh client public keys from Laravel.
        refresh_task = asyncio.create_task(_key_refresh_loop())
        stack.push_async_callback(lambda: refresh_task.cancel())

        # Periodically evict idle executors (refcount 0 past idle TTL).
        evict_task = asyncio.create_task(_executor_evict_loop())
        stack.push_async_callback(lambda: evict_task.cancel())

        yield


async def _refresh_client_keys() -> None:
    """Fetch the client_id -> public_key map from Laravel's internal endpoint.

    Python has no DB connection, so Laravel is the source of truth. The endpoint
    is loopback-only (LocalhostOnly middleware), so no signature is needed.
    Best-effort on failure.
    """
    url = (settings.ADMIN_LARAVEL_URL or "").rstrip("/") + "/api/internal/public-keys"
    if not url.startswith("http"):
        logger.warning("KeyStore refresh skipped: ADMIN_LARAVEL_URL not configured")
        return
    try:
        async with httpx.AsyncClient(timeout=10.0) as client:
            resp = await client.get(url)
            resp.raise_for_status()
            data = resp.json()
            key_store.refresh_client_keys({str(k): v for k, v in data.get("clients", {}).items()})
    except Exception as e:
        logger.warning("KeyStore refresh failed: %s", e)


async def _key_refresh_loop() -> None:
    """Background loop refreshing client keys every PUBLIC_KEYS_REFRESH_SEC."""
    await asyncio.sleep(2)
    while True:
        await _refresh_client_keys()
        await asyncio.sleep(settings.PUBLIC_KEYS_REFRESH_SEC)


async def _executor_evict_loop() -> None:
    """Background loop closing idle executors every EXECUTOR_EVICT_INTERVAL_SEC."""
    interval = max(30, _EXECUTOR_IDLE_TTL_SEC // 6)
    await asyncio.sleep(interval)
    while True:
        try:
            await executor_cache.evict_idle()
        except Exception:
            logger.exception("ExecutorCache eviction error")
        await asyncio.sleep(interval)


