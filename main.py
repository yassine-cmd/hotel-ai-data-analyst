@app.get("/internal/sessions/{client_id}/{session_id}/history")
async def get_session_history(client_id: str, session_id: str, request: Request):
    await _verify_request(request, require_admin=False, client_id_override=client_id)
    logger.info("GET /internal/sessions/%s/%s/history", client_id, session_id)
    try:
        history = await session_manager.get_history(session_id, client_id)
        session_error = await session_manager.get_session_error(session_id, client_id)
        session = await session_manager.get_or_create(session_id, client_id)
        raw_dfs = session.get("dataframes", {})
        dataframes = {}
        for name, meta in raw_dfs.items():
            shape = meta.get("shape") if isinstance(meta, dict) else getattr(meta, "shape", [0, 0])
            dtypes = meta.get("dtypes") if isinstance(meta, dict) else getattr(meta, "dtypes", [])
            dataframes[name] = {
                "shape": shape,
                "dtypes": dtypes,
                "download_url": f"/internal/sessions/{client_id}/{session_id}/artifacts/{name}/download",
            }
        return {
            "history": history,
            "workspace": {"dataframes": dataframes},
            "session_error": session_error,
        }
    except Exception as e:
        logger.error("Failed to get history for session %s: %s", session_id, e, exc_info=True)
        raise HTTPException(status_code=500, detail="Failed to retrieve session history")


@app.get("/internal/sessions/{client_id}/{session_id}/artifacts/{df_name}/download")
async def download_csv(client_id: str, session_id: str, df_name: str, request: Request):
    await _verify_request(request, require_admin=False, client_id_override=client_id)
    try:
        df = await session_manager.store.get(client_id, session_id, df_name)
    except Exception as e:
        logger.exception("download_csv unexpected error | %s/%s/%s", client_id, session_id, df_name)
        raise HTTPException(status_code=400, detail="Failed to download DataFrame")
    if df is None:
        raise HTTPException(status_code=404, detail="DataFrame not found")
    try:
        csv_text = df.to_csv(index=False)
    except Exception as e:
        logger.warning("download_csv conversion failed | %s/%s/%s | %s", client_id, session_id, df_name, e)
        raise HTTPException(status_code=500, detail="Failed to convert DataFrame to CSV")
    logger.info("download_csv success | %s/%s/%s | rows=%d", client_id, session_id, df_name, len(df))
    return Response(
        content=csv_text,
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{df_name}.csv"'},
    )


